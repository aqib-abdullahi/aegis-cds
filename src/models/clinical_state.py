from typing import Literal, Optional
from pydantic import BaseModel, Field


class PatientFact(BaseModel):
    """A single, verifiable clinical fact extracted from the patient's chart"""
    fact_id: str = Field(..., description="Unique trackin ID")
    category: Literal["demographics", "condition", "medication", "lab"]
    label: str = Field(..., description="Human-readable medical term")
    value: str = Field(..., description="Result, dosage or clinical status")
    code: Optional[str] = Field(None, description="standart medical code (SNOMED, LOINC, RxNorm)")
    timestamp: Optional[str] = Field(None, description="When thi fact wwas recorded")

class ClinicalHypothesis(BaseModel):
    """Inital clinical assess generated by the case synthesis agent"""
    hypothesis_id: str = Field(..., description="Unique ID like H-01, H-02")
    condition_or_risk: str = Field(..., description="Suspected condition, complication or medication risk")
    reasoning: str = Field(..., description="Concise clinical explanation grounded in facts")
    supporting_fact_ids: list[str] = Field(..., description="must cite exact fact_ids like ['F-01', F-03]")
    confidence: float = Field(..., ge=0.0, le=1.0, description="confidence scoring between 0.0 and 1.0")
    
class ClinicalState(BaseModel):
    """Shared state object passed between agents"""
    case_id: str
    phi_scrubbed: bool = Field(default=False, description="True only after names/IDs are stripped")
    patient_age: Optional[int] = None
    patient_gender: Optional[str] = None
    patient_facts: list[PatientFact] = Field(default_factory=list)
    initial_hypotheses: list[ClinicalHypothesis] = Field(default_factory=list)